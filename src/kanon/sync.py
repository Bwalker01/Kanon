"""`kanon sync`: regenerate the agent files Kanon keeps out of Git.

Generated files are rebuilt from the installed package, the project's committed standard and the
person's profile. Each carries a marker line; a file at a generated path without the marker was
written by someone else and is never overwritten.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from kanon import profile as profiles
from kanon.schema import split_frontmatter
from kanon.templates import CLAUDE_FILES, render

MARKER = "<!-- Generated by kanon sync. Do not edit: changes are overwritten. -->"
RULES = ".claude/rules/kanon.md"
PERSON = ".claude/rules/kanon-person.md"
GENERATED = [RULES, PERSON, *CLAUDE_FILES]
GENERATED_DIRS = ["kanon/local/"]
IGNORE_START, IGNORE_END = "# kanon:start (generated by kanon; do not edit)", "# kanon:end"

LEVEL_GUIDANCE = {
    "new-to-software": "New to software. Use plain language, explain each step and its purpose, and give exact commands to copy.",
    "some-experience": "Some experience. Name tools and commands and explain them on first use; omit basics.",
    "developer": "Developer. Use precise technical language; explain only specialised material.",
    "specialist": "Specialist. Speak as a peer; lead with trade-offs and evidence.",
}


@dataclass
class SyncResult:
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    refused: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def is_generated(text: str) -> bool:
    """True only when the marker sits at its fixed position: line one, or just after the frontmatter."""
    lines = text.split("\n")
    if lines and lines[0] == MARKER:
        return True
    if lines and lines[0] == "---":
        for index in range(1, len(lines)):
            if lines[index] == "---":
                return index + 1 < len(lines) and lines[index + 1] == MARKER
    return False


def _mark(text: str) -> str:
    """Insert the marker after any frontmatter, so the file stays valid for its reader."""
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + len("\n---\n")
        return text[:end] + MARKER + "\n" + text[end:]
    return MARKER + "\n" + text


def person_rules(person: profiles.Profile | None) -> str:
    if person is None:
        body = ("No Kanon profile was found for this person. At first contact, ask how they would describe "
                "their technical background (new to software, some experience, developer, specialist) and how "
                "they like to work, then suggest they run `kanon profile` to save it outside the repository.")
        return render("rules-person.md", who="This Person", profile_body=body)
    lines = [f"- **Technical level:** {LEVEL_GUIDANCE.get(person.level, 'Not set; ask at first contact.')}"]
    if person.description:
        lines.append(f"- **In their words:** {person.description}")
    if person.github:
        lines.append(f"- **GitHub:** `{person.github}`")
    lines += [f"- {p}" for p in person.preferences]
    lines.append(f"- **Profile source:** {person.source}. Suggest changes to the person; never edit it without their confirmation.")
    return render("rules-person.md", who=person.name or person.github or "This Person", profile_body="\n".join(lines))


def kanon_rules(root: Path) -> str:
    conduct_path = root / "kanon/docs/conduct-and-writing.md"
    if conduct_path.exists():
        _, body = split_frontmatter(conduct_path.read_text(encoding="utf-8"))
        conduct = re.sub(r"^# .*\n", "", body.strip() + "\n", count=1).strip()
        conduct = re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", conduct, flags=re.MULTILINE)
    else:
        conduct = "The standard is missing; run `kanon init`."
    return render("rules-kanon.md", conduct=conduct)


def expected_files(root: Path, person: profiles.Profile | None) -> dict[str, str]:
    files = {RULES: kanon_rules(root), PERSON: person_rules(person)}
    files.update({dest: render(src) for dest, src in CLAUDE_FILES.items()})
    return {path: _mark(text) for path, text in files.items()}


def ensure_gitignore(root: Path) -> bool:
    """Add or refresh the Kanon block in .gitignore. Returns True if the file changed."""
    path = root / ".gitignore"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    block = "\n".join([IGNORE_START, *(f"/{p}" for p in GENERATED + GENERATED_DIRS), IGNORE_END]) + "\n"
    starts, ends = text.count(IGNORE_START), text.count(IGNORE_END)
    if starts == 0 and ends == 0:
        new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    elif starts == 1 and ends == 1 and text.index(IGNORE_START) < text.index(IGNORE_END):
        start, end = text.index(IGNORE_START), text.index(IGNORE_END) + len(IGNORE_END)
        new = text[:start] + block.rstrip("\n") + text[end:]
    else:
        raise ValueError(".gitignore has a damaged Kanon block (markers missing, repeated or out of order); "
                         "fix or remove it by hand, then run kanon sync again")
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def sync(root: Path) -> SyncResult:
    result = SyncResult()
    try:
        person = profiles.load()
    except ValueError as error:
        person = None
        result.notes.append(f"profile ignored: {error}")
    if person is None:
        result.notes.append("no profile found; agents will ask at first contact (see `kanon profile`)")
    else:
        result.notes += [f"profile problem: {p.message}" for p in profiles.validate(person)]
    try:
        if ensure_gitignore(root):
            result.written.append(".gitignore")
    except ValueError as error:
        result.notes.append(str(error))
        result.refused.append(".gitignore")
    for rel, content in expected_files(root, person).items():
        path = root / rel
        if path.exists():
            current = path.read_text(encoding="utf-8")
            if current == content:
                result.unchanged.append(rel)
                continue
            if not is_generated(current):
                result.refused.append(rel)
                continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        result.written.append(rel)
    if (root / "kanon/kanon.toml").exists():
        from kanon import desk
        desk.write(root)
        result.written += list(desk.OUTPUTS)
    return result

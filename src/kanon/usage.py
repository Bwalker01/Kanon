"""Token usage and cost for a time window, read from Claude Code session logs (P1-07).

Claude Code writes one JSON line per content block, so a single reply can appear several
times with the same message id and the same usage. Replies are counted once per id.
Cost comes only from Claude Code's own cumulative estimate (`cost-state` records); Kanon
keeps no price list of its own. Anything the reader does not recognise is reported as
unknown rather than as zero.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

TOKEN_FIELDS = ("output_tokens", "input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")


@dataclass
class Totals:
    replies: int = 0
    tokens: dict[str, int] = field(default_factory=lambda: dict.fromkeys(TOKEN_FIELDS, 0))

    def add(self, usage: dict) -> None:
        self.replies += 1
        for key in TOKEN_FIELDS:
            self.tokens[key] += int(usage.get(key) or 0)


@dataclass
class UsageReport:
    since: dt.datetime | None
    until: dt.datetime | None
    main: Totals
    subagents: Totals
    cost_usd: float | None
    status: str  # "ok", "empty" or "unknown"
    notes: list[str]
    cost_bound: str = "unknown"  # "at-most", "incomplete" or "unknown"

    def as_dict(self) -> dict:
        return {
            "since": self.since.isoformat() if self.since else None,
            "until": self.until.isoformat() if self.until else None,
            "status": self.status,
            "main": {"replies": self.main.replies, **self.main.tokens},
            "subagents": {"replies": self.subagents.replies, **self.subagents.tokens},
            "estimated_cost_usd": self.cost_usd,
            "cost_bound": self.cost_bound,
            "notes": self.notes,
        }


def default_log_dir(repo: Path) -> Path:
    """Claude Code stores logs per project, named after the path with separators replaced."""
    base = Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude"))
    return base / "projects" / re.sub(r"[^A-Za-z0-9]", "-", str(repo.resolve()))


def parse_time(value: str, repo: Path | None = None) -> dt.datetime:
    """Accept an ISO 8601 timestamp (UTC if no offset) or a git reference (its commit time)."""
    if value.startswith("-"):
        raise ValueError(f"'{value}' is neither an ISO timestamp nor a git reference")
    try:
        parsed = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        result = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--end-of-options", value],
            cwd=repo, capture_output=True, text=True,
        )
        if result.returncode != 0 or not result.stdout.strip():
            raise ValueError(f"'{value}' is neither an ISO timestamp nor a git reference") from None
        parsed = dt.datetime.fromisoformat(result.stdout.strip())
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=dt.timezone.utc)


def _entries(path: Path):
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue  # a line still being written, or a corrupt line
            if isinstance(entry, dict):
                yield entry


def _in_window(stamp: dt.datetime, since, until) -> bool:
    return (since is None or stamp >= since) and (until is None or stamp < until)


@dataclass
class _Reply:
    when: dt.datetime
    session: str
    usage: dict


def _read_replies(files: list[Path]) -> tuple[dict[str, _Reply], int]:
    """Every reply once, timed by its first log entry. Returns replies and unreadable entries."""
    replies: dict[str, _Reply] = {}
    unreadable = 0
    for path in files:
        for entry in _entries(path):
            message = entry.get("message")
            if entry.get("type") != "assistant" or not isinstance(message, dict):
                continue
            if message.get("model") == "<synthetic>":
                continue  # generated by Claude Code itself, not a model reply
            usage, message_id, stamp = message.get("usage"), message.get("id"), entry.get("timestamp")
            if not (isinstance(usage, dict) and isinstance(usage.get("output_tokens"), int)
                    and isinstance(message_id, str) and isinstance(stamp, str)):
                unreadable += 1
                continue
            try:
                when = parse_time(stamp)
            except ValueError:
                unreadable += 1
                continue
            fallback = path.parent.parent.name if path.parent.name == "subagents" else path.stem
            session = str(entry.get("sessionId") or fallback)
            if message_id not in replies or when < replies[message_id].when:
                replies[message_id] = _Reply(when, session, usage)
    return replies, unreadable


def _totals(replies: dict[str, _Reply], since, until) -> Totals:
    totals = Totals()
    for reply in replies.values():
        if _in_window(reply.when, since, until):
            totals.add(reply.usage)
    return totals


def _cost_points(main_files: list[Path]):
    """Claude Code's cumulative estimate per session, and the times each session was active.

    Returns ({session: [(time, total USD, unknown-model flag)]}, {session: [entry times]}).
    """
    sessions: dict[str, list[tuple[dt.datetime, float, bool]]] = {}
    activity: dict[str, list[dt.datetime]] = {}
    for path in main_files:
        last_seen: dt.datetime | None = None
        for entry in _entries(path):
            if isinstance(entry.get("timestamp"), str):
                try:
                    last_seen = parse_time(entry["timestamp"])
                    activity.setdefault(str(entry.get("sessionId") or path.stem), []).append(last_seen)
                except ValueError:
                    pass
            if entry.get("type") == "cost-state" and isinstance(entry.get("totalCostUSD"), (int, float)):
                if last_seen is not None:
                    session = str(entry.get("sessionId") or path.stem)
                    unknown = bool(entry.get("hasUnknownModelCost"))
                    sessions.setdefault(session, []).append((last_seen, float(entry["totalCostUSD"]), unknown))
    for points in sessions.values():
        points.sort(key=lambda p: p[0])
    return sessions, activity


@dataclass(frozen=True)
class Cost:
    usd: float | None
    bound: str  # "at-most", "incomplete" or "unknown"


def _cost(main_files, replies: dict[str, _Reply], since, until, notes: list[str]) -> Cost:
    """Sum, per session, the change in Claude Code's running estimate across the window.

    The window is widened to the nearest estimate records, so a complete figure is an upper
    bound. Replies after a session's last record are not yet costed: the figure is incomplete.
    """
    sessions, activity = _cost_points(main_files)
    in_window = [r for r in replies.values() if _in_window(r.when, since, until)]
    if not sessions:
        return Cost(None, "unknown")
    total, incomplete, unknown_model, decreased = 0.0, 0, False, False
    for session, points in sessions.items():
        if not any(_in_window(when, since, until) for when in activity.get(session, [])):
            continue  # the session did nothing in this window, so it adds nothing
        start = [p for p in points if since is not None and p[0] <= since]
        start_cost = start[-1][1] if start else 0.0
        after = [p for p in points if until is not None and p[0] >= until]
        end = after[0] if after else points[-1]
        used = [p for p in points if (not start or p[0] >= start[-1][0]) and p[0] <= end[0]]
        unknown_model = unknown_model or any(p[2] for p in used)
        if end[1] < start_cost:
            decreased = True
        total += end[1] - start_cost
        incomplete += sum(1 for r in in_window if r.session == session and r.when > points[-1][0])
    known = set(sessions)
    incomplete += sum(1 for r in in_window if r.session not in known and not r.session.startswith("agent-"))
    if decreased:
        notes.append("Claude Code's running cost estimate went down during the window; cost unavailable")
        return Cost(None, "unknown")
    if unknown_model:
        notes.append("Claude Code reports a model with unknown pricing; cost unavailable")
        return Cost(None, "unknown")
    if incomplete:
        notes.append(f"{incomplete} replies come after Claude Code's latest cost estimate; "
                     "the cost shown is incomplete. Re-run after the session's next turn")
        return Cost(round(total, 2), "incomplete")
    notes.append("cost is an upper bound: Claude Code updates its estimate about once per turn, "
                 "so the window is widened to the nearest estimates")
    return Cost(round(total, 2), "at-most")


def report(log_dir: Path, since=None, until=None) -> UsageReport:
    notes: list[str] = []
    if not log_dir.is_dir():
        return UsageReport(since, until, Totals(), Totals(), None, "unknown",
                           [f"no Claude Code logs found at {log_dir}"], "unknown")
    main_files = sorted(log_dir.glob("*.jsonl"))
    sub_files = sorted(log_dir.glob("*/subagents/*.jsonl"))
    main_replies, bad_main = _read_replies(main_files)
    sub_replies, bad_subs = _read_replies(sub_files)
    main, subs = _totals(main_replies, since, until), _totals(sub_replies, since, until)
    cost = _cost(main_files, main_replies | sub_replies, since, until, notes)
    if cost.bound == "unknown" and cost.usd is None and not any("pricing" in n for n in notes):
        notes.append("no cost estimate found in the logs")

    bad = bad_main + bad_subs
    if bad and main.replies + subs.replies == 0:
        return UsageReport(since, until, main, subs, None, "unknown",
                           notes + [f"{bad} assistant entries in an unrecognised format"], "unknown")
    if bad:
        notes.append(f"{bad} assistant entries skipped: unrecognised format")
    status = "ok" if main.replies + subs.replies else "empty"
    if status == "empty":
        notes.append("no replies in this window")
    return UsageReport(since, until, main, subs, cost.usd, status, notes, cost.bound)


def cost_text(rep: UsageReport) -> str:
    if rep.cost_usd is None:
        return "unavailable"
    if rep.cost_bound == "incomplete":
        return f"incomplete: ${rep.cost_usd:.2f} so far"
    return f"at most ${rep.cost_usd:.2f}"


def format_report(rep: UsageReport) -> str:
    if rep.status == "unknown":
        return "Usage: unknown\n" + "\n".join(f"  - {n}" for n in rep.notes)
    rows = [("", "Main session", "Subagents")]
    for label, key in (("Output tokens", "output_tokens"), ("Cache writes", "cache_creation_input_tokens"),
                       ("Cache reads", "cache_read_input_tokens"), ("Uncached input", "input_tokens")):
        rows.append((label, f"{rep.main.tokens[key]:,}", f"{rep.subagents.tokens[key]:,}"))
    rows.append(("Replies", str(rep.main.replies), str(rep.subagents.replies)))
    widths = [max(len(r[i]) for r in rows) for i in range(3)]
    lines = ["  ".join(c.ljust(widths[i]) if i == 0 else c.rjust(widths[i]) for i, c in enumerate(r)) for r in rows]
    suffix = "" if rep.cost_usd is None else " (Claude Code estimate, API-equivalent)"
    lines.append(f"Estimated cost: {cost_text(rep)}{suffix}")
    lines.extend(f"Note: {n}" for n in rep.notes)
    return "\n".join(lines)


COST_HEADER = "| Step | Output (main) | Output (subagents) | Cache writes | Cache reads | Estimated cost |"


def record(rep: UsageReport, work_file: Path, label: str) -> None:
    """Append a row for this window to the Cost section of a work file, keeping its line endings."""
    with work_file.open(encoding="utf-8", newline="") as handle:
        raw = handle.read()
    newline = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.replace("\r\n", "\n").split("\n")
    start = next((n for n, line in enumerate(lines) if re.fullmatch(r"## (?:\d+\.\s+)?Cost\s*", line)), None)
    if start is None:
        raise ValueError(f"{work_file} has no Cost section")
    end = next((n for n in range(start + 1, len(lines)) if lines[n].startswith("## ")), len(lines))

    if rep.status == "unknown":
        cells = [label] + ["unknown"] * 5
    else:
        tokens = lambda key: rep.main.tokens[key] + rep.subagents.tokens[key]  # noqa: E731
        cells = [label, f"{rep.main.tokens['output_tokens']:,}", f"{rep.subagents.tokens['output_tokens']:,}",
                 f"{tokens('cache_creation_input_tokens'):,}", f"{tokens('cache_read_input_tokens'):,}",
                 cost_text(rep)]
    row = "| " + " | ".join(cells) + " |"

    header = next((n for n in range(start, end) if lines[n] == COST_HEADER), None)
    if header is not None:
        last = header
        while last + 1 < end and lines[last + 1].startswith("|"):
            last += 1
        lines.insert(last + 1, row)
    else:
        insert_at = end
        while insert_at > start + 1 and lines[insert_at - 1] == "":
            insert_at -= 1
        block = ["", COST_HEADER, "|---|---|---|---|---|---|", row]
        if end < len(lines):
            block.append("")
        lines[insert_at:insert_at] = block
    with work_file.open("w", encoding="utf-8", newline="") as handle:
        handle.write(newline.join(lines))
